"""Prepare the static GitHub Pages entry from the canonical local HTML."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MARKER = "<!-- Generated by tools/prepare_pages.py from MIRA_3Dフォルダ読込版.html. -->\n"


def main():
    source = ROOT / "MIRA_3Dフォルダ読込版.html"
    target = ROOT / "index.html"
    if target.exists() and not target.read_text(encoding="utf-8").startswith(MARKER):
        raise RuntimeError("index.html is not this tool's generated entry; left unchanged")
    html = source.read_text(encoding="utf-8")
    # Archived fixed-data viewers require local-only data and are not public app navigation.
    html = html.replace('<a href="archive/index.html" target="_blank" rel="noopener">旧版アーカイブ</a>', "")
    for ref in re.findall(r'(?:src|href)="([^"#]+)"', html):
        path = (ROOT / ref).resolve()
        if not path.is_relative_to(ROOT) or not path.is_file():
            raise RuntimeError(f"Missing or external static asset: {ref}")
    target.write_text(MARKER + html, encoding="utf-8")
    (ROOT / ".nojekyll").touch()
    print("Prepared index.html and .nojekyll; measurement data was not read or copied.")


if __name__ == "__main__":
    main()
